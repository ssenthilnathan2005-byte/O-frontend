const NLEM_RE = NLEM_GENERICS.map(g => new RegExp("\\b" + g.replace(/ /g, "\\s+") + "\\b", "i"));

export function isNlem(medicineName: string): boolean {
  const s = (medicineName || "").trim();
  if (s.length < 3) return false;
  return NLEM_RE.some(re => re.test(s));
}
